package TEMA_5;

public class PruebaBucles {
    public static void main(String[] args) {

        //PRUEBA DE BUCLES
        int i;
        System.out.println("Empiezo a ejecutar el bucle");

        for (i=1;i<=10; i++){
            System.out.printf("Estoy en la ejecución %d%n", i);
        }

        System.out.println("Ya ha acabado el bucle");
        //QUE VALOR TIENE i AL ACABAR EL BUCLE
        System.out.printf("La variable i vale en este punto %d%n",i);
    }
}
